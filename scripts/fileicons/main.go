// Command fileicons brings Pierre's file icons (github.com/pierrecomputer/vscode-icons,
// MIT) into kero: from a checkout of theirs, built with `node
// scripts/build-icon-theme.mjs`, the icons of the complete theme, in their
// light and dark colors, go to icons/files, and the names, extensions and
// defaults they are for to fileicons_gen.go.
//
//	go run ./scripts/fileicons ~/src/vscode-icons
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

type theme struct {
	IconDefinitions map[string]struct {
		IconPath string `json:"iconPath"`
	} `json:"iconDefinitions"`
	File           string            `json:"file"`
	Folder         string            `json:"folder"`
	FolderExpanded string            `json:"folderExpanded"`
	FileSymlink    string            `json:"fileSymlink"`
	FileExtensions map[string]string `json:"fileExtensions"`
	FileNames      map[string]string `json:"fileNames"`
	FolderNames    map[string]string `json:"folderNames"`
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: go run ./scripts/fileicons <checkout of pierrecomputer/vscode-icons, built>")
	}
	src := filepath.Join(os.Args[1], "icons")
	b, err := os.ReadFile(filepath.Join(src, "theme-complete.json"))
	if err != nil {
		log.Fatal(err)
	}
	var t theme
	if err := json.Unmarshal(b, &t); err != nil {
		log.Fatal(err)
	}

	// The icons, by their names: name.svg for the dark appearance,
	// name_light.svg for the light one.
	out := filepath.Join("icons", "files")
	os.RemoveAll(out)
	if err := os.MkdirAll(out, 0o755); err != nil {
		log.Fatal(err)
	}
	for name, d := range t.IconDefinitions {
		svg, err := os.ReadFile(filepath.Join(src, d.IconPath))
		if err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(out, name+".svg"), svg, 0o644); err != nil {
			log.Fatal(err)
		}
	}

	// Their license, which goes with them.
	lic, err := os.ReadFile(filepath.Join(os.Args[1], "LICENSE.md"))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(out, "LICENSE.md"), lic, 0o644); err != nil {
		log.Fatal(err)
	}

	var g bytes.Buffer
	g.WriteString("// Code generated by go run ./scripts/fileicons; DO NOT EDIT.\n\npackage main\n\n")
	fmt.Fprintf(&g, "var fileIconTheme = iconTheme{\n\tfile: %q,\n\tfolder: %q,\n\tfolderOpen: %q,\n\tsymlink: %q,\n", t.File, t.Folder, t.FolderExpanded, t.FileSymlink)
	writeMap(&g, "names", t.FileNames)
	writeMap(&g, "extensions", t.FileExtensions)
	writeMap(&g, "folders", t.FolderNames)
	g.WriteString("}\n")
	src2, err := format.Source(g.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("fileicons_gen.go", src2, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d icons, %d names, %d extensions\n", len(t.IconDefinitions), len(t.FileNames), len(t.FileExtensions))
}

// writeMap writes a map of names, which kero matches without regard to
// case, as VS Code does.
func writeMap(g *bytes.Buffer, field string, m map[string]string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	fmt.Fprintf(g, "\t%s: map[string]string{\n", field)
	for _, k := range keys {
		fmt.Fprintf(g, "\t\t%q: %q,\n", strings.ToLower(k), m[k])
	}
	g.WriteString("\t},\n")
}
